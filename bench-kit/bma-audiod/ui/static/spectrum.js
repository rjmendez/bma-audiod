  /* the persistence ("phosphor") histogram: H[band][level cell] accumulates one count per row and decays exponentially with time constant tau.
     A row value v adds 1 to its cell and 0.25 to the two neighbouring cells (steady tones read as lines). Intensity of a cell with count h:
     min(1, log1p(G h) / log1p(G Hnorm)), Hnorm = tau * rows_per_s = the steady-state count of a cell hit by every row. */
  const GAIN = 8, SMEAR = 0.25;
  function Persistence(nBins, tau, rowsPerS) {
    this.n = nBins; this.tau = tau; this.rate = rowsPerS; this.H = new Float32Array(nBins * LEVELS); this.P = new Float32Array(nBins); this.hasPeak = false;
  }
  Persistence.prototype.norm = function () { return this.tau * this.rate; };
  Persistence.prototype.decay = function (dt) { if (!(dt > 0)) return; const f = Math.exp(-dt / this.tau), H = this.H; for (let i = 0; i < H.length; i++) H[i] *= f; };
  Persistence.prototype.hit = function (bin, v) {
    const H = this.H, k = bin * LEVELS, w = arguments.length > 2 ? arguments[2] : 1; H[k + v] += w;
    if (v > 0) H[k + v - 1] += SMEAR * w; if (v < LEVELS - 1) H[k + v + 1] += SMEAR * w;
  };
  Persistence.prototype.addRow = function (bins, w) {
    if (w === undefined) w = 1;
    for (let b = 0; b < this.n; b++) { this.hit(b, bins[b], w); if (!this.hasPeak || bins[b] > this.P[b]) this.P[b] = bins[b]; }
    this.hasPeak = true;
  };
  Persistence.prototype.decayPeak = function (dt, dbPerS, step) { const d = dbPerS * dt / step; for (let b = 0; b < this.n; b++) this.P[b] = Math.max(0, this.P[b] - d); };
  Persistence.prototype.resetPeak = function () { this.P.fill(0); this.hasPeak = false; };
  Persistence.prototype.intensity = function (h) { return Math.min(1, Math.log1p(GAIN * h) / Math.log1p(GAIN * this.norm())); };
  Core.Persistence = Persistence;
  /* 1024-entry table: histogram count (0..1.3 Hnorm) -> colour index 1..255, 0 = nothing drawn */
