#!/usr/bin/env python3
"""Writes static/engine/colormaps.js: 256-entry tables (r, g, b hex) for viridis, magma, inferno, cividis (matplotlib, CC0) and turbo (Google, Apache-2.0).
    python make_colormaps.py        (needs matplotlib; run from this directory)
viridis/cividis are perceptually uniform and colour-blind safe: the defaults. Turbo is for contrast on noisy data only."""
import matplotlib

names = ("viridis", "magma", "inferno", "cividis", "turbo")
lines = ["/* generated by make_colormaps.py: matplotlib colormaps (viridis, magma, inferno, cividis: CC0; turbo: Apache-2.0, Google). index 0 = lowest level. */",
         "(function (root) {", "  root.LabColormaps = {"]
for n in names:
    cm = matplotlib.colormaps[n]
    hx = "".join("%02x%02x%02x" % tuple(int(round(c * 255)) for c in cm(i / 255.0)[:3]) for i in range(256))
    lines.append('    %s: "%s",' % (n, hx))
lines += ["  };", "})(typeof self !== 'undefined' ? self : this);", ""]
open("static/engine/colormaps.js", "w", encoding="ascii", newline="\n").write("\n".join(lines))
print("ok", [n for n in names])
