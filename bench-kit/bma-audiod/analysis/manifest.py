#!/usr/bin/env python3
"""The analysis plugin manifest: reader, validator and derivations (stdlib only; docs/design/w3-plugin-manifest.md).

analysis/plugins.manifest.json is the one registry of the analyzer's plugins. This module loads and validates it and derives
everything the other files used to list by hand: the host's help text and flags, the module imports, the plugin factories, the
status meta counters, the install lists (pc/install_task.ps1 and docker/analyzer.Dockerfile), the contract tables of
contracts/check_contracts.py and the README plugin table.

    python manifest.py check                                    # validate the manifest against the files on disk
    python manifest.py install --target pc|image --dest DIR [--dry-run]   # copy (or list) the analysis files of one target
    python manifest.py readme [--write]                         # print / refresh the generated README block
    python manifest.py list                                     # plugin names in registration order

Runs next to host.py, from the repository or from a flat installed app directory (only analysis/ files are needed)."""

import ast, importlib, json, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
BMA = os.path.dirname(HERE)
MANIFEST = os.path.join(HERE, "plugins.manifest.json")
CLI_SLOTS = ("geo", "plugins", "tail")
FLAG_TYPES = {"int": int, "float": float, "str": str}
IMPORTS = ("required", "optional", "lazy")
TARGETS = ("pc", "image")
HOOK_METHODS = {"consumes_speech": "note_speech", "consumes_tag": "note_tag", "observes": "observe", "cost": "cost", "flush": "flush"}
HOOK_FLAGS = set(HOOK_METHODS) | {"stats_in_status", "window_info_to_daily"}
FEEDS = ("tags_feed", "birds_to_perch", "clips", "speech_guard")
README_BEGIN = "<!-- BEGIN plugin-table (generated by analysis/manifest.py readme --write; do not edit by hand, regenerate) -->"
README_END = "<!-- END plugin-table -->"


class ManifestError(Exception):
    """The manifest is wrong (or disagrees with the files on disk); the message names the entry."""


class HookError(RuntimeError):
    """A plugin instance does not implement a hook its manifest entry declares."""


# ------------------------------------------------------------------ load
def check_text(raw):
    """The file hygiene the PowerShell and Docker readers rely on: no BOM, no CR, no tab."""
    if raw.startswith(b"\xef\xbb\xbf"):
        raise ManifestError("manifest has a UTF-8 BOM (PowerShell 5.1 and json.load disagree about it)")
    if b"\r" in raw:
        raise ManifestError("manifest has CR characters (LF only)")
    if b"\t" in raw:
        raise ManifestError("manifest has tab characters (2-space indent)")


def loads(raw):
    """bytes -> manifest dict, hygiene-checked."""
    check_text(raw)
    try:
        return json.loads(raw.decode("utf-8"))
    except ValueError as e:
        raise ManifestError(f"manifest is not valid JSON: {e}") from None


def load(path=MANIFEST):
    with open(path, "rb") as f:
        return loads(f.read())


def plugins(m):
    return m["plugins"]


def by_name(m):
    return {e["name"]: e for e in m["plugins"]}


def hooks(entry):
    return entry.get("hooks") or {}


# ------------------------------------------------------------------ validate
def _class_info(path, plugin_name):
    """AST scan of one module file -> (class name, heavy attribute or None, {method names}) of the class whose `name` attribute
    is plugin_name, or None."""
    with open(path, "r", encoding="utf-8") as f:
        tree = ast.parse(f.read())
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        attrs, methods = {}, set()
        for st in node.body:
            if isinstance(st, ast.Assign):
                for t in st.targets:
                    if isinstance(t, ast.Name) and isinstance(st.value, ast.Constant):
                        attrs[t.id] = st.value.value
                    elif isinstance(t, ast.Tuple) and isinstance(st.value, ast.Tuple):  # `win_s, hop_s = 5.0, 2.0`
                        for tt, vv in zip(t.elts, st.value.elts):
                            if isinstance(tt, ast.Name) and isinstance(vv, ast.Constant):
                                attrs[tt.id] = vv.value
            elif isinstance(st, ast.FunctionDef):
                methods.add(st.name)
        if attrs.get("name") == plugin_name:
            return node.name, attrs.get("heavy"), methods
    return None


def _top_level_functions(path):
    with open(path, "r", encoding="utf-8") as f:
        return {n.name for n in ast.parse(f.read()).body if isinstance(n, ast.FunctionDef)}


def validate(m, analysis_dir=HERE, check_files=True):
    """Raise ManifestError naming the entry when the manifest is malformed or disagrees with analysis_dir. check_files=False
    checks the structure only."""
    if m.get("manifest_version") != 1:
        raise ManifestError(f"manifest_version must be 1, found {m.get('manifest_version')!r}")
    for k in ("support_files", "pc_only_files", "extra_files", "legacy_order", "plugins"):
        if k not in m:
            raise ManifestError(f"manifest has no {k!r}")
    seen, flags_seen = set(), {}
    for e in m["plugins"]:
        n = e.get("name")
        if not isinstance(n, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", n):
            raise ManifestError(f"plugin name {n!r} is not a lowercase identifier")
        if n in seen:
            raise ManifestError(f"duplicate plugin name {n!r}")
        seen.add(n)
        for k in ("module", "files", "import", "make", "heavy", "deploy", "outputs"):
            if k not in e:
                raise ManifestError(f"plugin {n!r}: missing key {k!r}")
        if e["import"] not in IMPORTS:
            raise ManifestError(f"plugin {n!r}: import must be one of {IMPORTS}, found {e['import']!r}")
        if not isinstance(e["heavy"], bool):
            raise ManifestError(f"plugin {n!r}: heavy must be true or false")
        bad = [t for t in e["deploy"] if t not in TARGETS]
        if bad:
            raise ManifestError(f"plugin {n!r}: unknown deploy target(s) {bad} (known: {list(TARGETS)})")
        for f in e["files"]:
            if "/" in f or "\\" in f:
                raise ManifestError(f"plugin {n!r}: file {f!r} must be a bare name in analysis/")
        if e.get("cli_slot", "tail") not in CLI_SLOTS:
            raise ManifestError(f"plugin {n!r}: cli_slot {e.get('cli_slot')!r} is not one of {list(CLI_SLOTS)}")
        for fl in e.get("flags", []):
            if not fl["name"].startswith("--"):
                raise ManifestError(f"plugin {n!r}: flag {fl['name']!r} must start with --")
            if fl.get("type") not in FLAG_TYPES and fl.get("type") != "flag":
                raise ManifestError(f"plugin {n!r}: flag {fl['name']} has type {fl.get('type')!r} (allowed: int, float, str, flag)")
            if fl["name"] in flags_seen:
                raise ManifestError(f"flag {fl['name']} is declared by both {flags_seen[fl['name']]!r} and {n!r}")
            flags_seen[fl["name"]] = n
        h = hooks(e)
        unknown = [k for k in h if k not in HOOK_FLAGS and k != "feeds"]
        if unknown:
            raise ManifestError(f"plugin {n!r}: unknown hook(s) {unknown}")
        for fd in h.get("feeds", []):
            if fd not in FEEDS:
                raise ManifestError(f"plugin {n!r}: unknown feed {fd!r} (known: {list(FEEDS)})")
        if ":" not in e["make"]:
            raise ManifestError(f"plugin {n!r}: make must be 'module:function', found {e['make']!r}")
    names = seen
    for e in m["plugins"]:
        for r in e.get("requires", []) + e.get("soft_needs", []):
            if r not in names:
                raise ManifestError(f"plugin {e['name']!r}: requires/soft_needs names unknown plugin {r!r}")
    lo = m["legacy_order"]
    for key, extra in (("no_help", set()), ("outputs", {"novelty"})):
        lst = lo.get(key, [])
        dup = sorted({x for x in lst if lst.count(x) > 1})
        if dup:
            raise ManifestError(f"legacy_order.{key} lists {dup} more than once")
        unk = [x for x in lst if x not in names and x not in extra]
        if unk:
            raise ManifestError(f"legacy_order.{key} names unknown plugin(s) {unk}")
    if not check_files:
        return
    for e in m["plugins"]:
        n = e["name"]
        mod_path = os.path.join(analysis_dir, e["module"] + ".py")
        if not os.path.isfile(mod_path):
            raise ManifestError(f"plugin {n!r}: module file {e['module']}.py not found in {analysis_dir}")
        for f in e["files"]:
            if not os.path.isfile(os.path.join(analysis_dir, f)):
                raise ManifestError(f"plugin {n!r}: file {f} not found in {analysis_dir}")
        mk_mod, _, mk_fn = e["make"].partition(":")
        mk_path = os.path.join(analysis_dir, mk_mod + ".py")
        if not os.path.isfile(mk_path) or mk_fn not in _top_level_functions(mk_path):
            raise ManifestError(f"plugin {n!r}: make {e['make']!r} does not name a function defined at the top level of {mk_mod}.py")
        info = _class_info(mod_path, n)
        if info is None:
            raise ManifestError(f"plugin {n!r}: no class with name = {n!r} in {e['module']}.py")
        cls, heavy, methods = info
        if heavy is not e["heavy"]:
            raise ManifestError(f"plugin {n!r}: manifest says heavy={e['heavy']} but class {cls}.heavy is {heavy}")
        h = hooks(e)
        for hk, meth in HOOK_METHODS.items():
            if bool(h.get(hk)) and meth not in methods:
                raise ManifestError(f"plugin {n!r}: hook {hk} is declared but class {cls} has no method {meth}()")
            if not h.get(hk) and meth in methods:
                raise ManifestError(
                    f"plugin {n!r}: class {cls} has method {meth}() but the manifest does not declare hook {hk} (declare it or rename the method)"
                )
        for c in e.get("meta_counters", []):
            if "stats" not in methods:
                raise ManifestError(f"plugin {n!r}: meta_counters need a stats() method on {cls}")
    for f in m["support_files"] + m["pc_only_files"]:
        if not os.path.isfile(os.path.join(analysis_dir, f)):
            raise ManifestError(f"support file {f} not found in {analysis_dir}")


# ------------------------------------------------------------------ text derived for host.py
def _ordered(m, key, extra_ok=()):
    """legacy order first, then the plugins it does not list in manifest order."""
    legacy = list(m["legacy_order"].get(key, []))
    return legacy, [e["name"] for e in m["plugins"] if e["name"] not in legacy]


def no_help_names(m):
    """Names in the `--no` help: the legacy order, then plugins not listed there, minus those with in_no_help false (the opt-in
    experiments, e.g. the pad lane, whose `--no` is accepted but never advertised)."""
    legacy, rest = _ordered(m, "no_help")
    skip = {e["name"] for e in m["plugins"] if e.get("in_no_help") is False}
    return [x for x in legacy + rest if x not in skip]


def outputs_names(m):
    """Stems in the host docstring's Outputs line: the legacy order (it includes `novelty`, which is no plugin), then plugins
    not listed there, minus those with in_docstring false."""
    legacy, rest = _ordered(m, "outputs")
    skip = {e["name"] for e in m["plugins"] if e.get("in_docstring") is False}
    return legacy + [x for x in rest if x not in skip]


def no_help_text(m):
    return "disable a plugin: " + " ".join(no_help_names(m)) + " (or `clips`: no wildlife clip capture)"


def fill_docstring(doc, m):
    """host.py's module docstring holds `{outputs}`; the generated text is the old hand-written one."""
    return doc.replace("{outputs}", "  ".join(n + ".jsonl" for n in outputs_names(m)) + "   + emb_YYYYMMDD.f16/.jsonl")


def add_flags(ap, m, slot):
    """Add the argparse flags of every plugin whose cli_slot is `slot`, in manifest order."""
    for e in m["plugins"]:
        if e.get("cli_slot", "tail") != slot:
            continue
        for fl in e.get("flags", []):
            kw = {"help": fl.get("help")}
            if fl["type"] == "flag":
                kw["action"] = "store_true"
            else:
                kw["type"] = FLAG_TYPES[fl["type"]]
                kw["default"] = fl.get("default")
            if "metavar" in fl:
                kw["metavar"] = fl["metavar"]
            ap.add_argument(fl["name"], **kw)


# ------------------------------------------------------------------ build
class Ctx:
    """What a plugin's make(ctx) may read (only what the old host.py lambdas closed over). `started` is the set of plugin names that
    started before this one; `shared` carries the explicit hand-offs between plugins (speech_guard)."""

    def __init__(self, args, taxa, dev, run_id, classify_dir, out_dir, started, shared, plug=None):
        self.plug = plug if plug is not None else []  # the running plugin instances, in start order (a plugin that shares another's model reads it here)
        self.args, self.taxa, self.dev, self.run_id = args, taxa, dev, run_id
        self.classify_dir, self.out_dir, self.started, self.shared = classify_dir, out_dir, started, shared


def resolve(spec):
    """'module:function' -> the function (imports the module)."""
    mod, _, fn = spec.partition(":")
    return getattr(importlib.import_module(mod), fn)


def load_modules(m):
    """Import the modules of the plugins with import 'required' (a failure propagates, as the old top-level import did) or 'optional'
    (a failure is recorded). -> {plugin name: {"type", "error", "warn", "reason"}} for the optional ones that failed. The legacy WARN
    line is printed by the caller (host.py) so its stream stays under the host's control."""
    failed = {}
    for e in m["plugins"]:
        if e["import"] == "lazy":
            continue
        if e["import"] == "required":
            importlib.import_module(e["module"])
            continue
        try:
            importlib.import_module(e["module"])
        except Exception as ex:  # optional plugin: a missing file or old scipy must not stop the analyzer
            d = {"type": type(ex).__name__, "error": str(ex)}
            tpl = e.get("import_reason") or "{type}: {error}"
            d["reason"] = tpl.format(**d)[:200]
            d["warn"] = (e.get("import_warn") or "WARN: " + e["name"] + " module not importable: {type}: {error}").format(**d)
            failed[e["name"]] = d
    return failed


def build(entry, ctx):
    """make(ctx) of one entry, then the declaration check: a hook the manifest declares must exist on the instance."""
    p = resolve(entry["make"])(ctx)
    verify_instance(entry, p)
    return p


def verify_instance(entry, p):
    h = hooks(entry)
    for hk, meth in HOOK_METHODS.items():
        if h.get(hk) and not callable(getattr(p, meth, None)):
            raise HookError(f"manifest declares hook {hk} for plugin {entry['name']} but {type(p).__name__} has no {meth}()")


def gate_closed(entry, args, no):
    """-> the status reason when the entry's gate keeps it off, else None. `--no x` gives the standard reason unless the gate wins."""
    g = entry.get("gate")
    if not g or getattr(args, g["flag"]):
        return None
    if entry["name"] in no and not g.get("beats_no"):
        return None
    return g["off_reason"]


def gate_silent(entry):
    """True when a closed gate leaves NO status entry at all (opt-in experiments that were never listed in status.json while off)."""
    return bool((entry.get("gate") or {}).get("silent"))


def meta_counters(m, running):
    """-> [(counter name, [instances], [stats keys], only_when_running)] for the running plugin instances `running` ({name: instance})."""
    out = []
    for e in m["plugins"]:
        for c in e.get("meta_counters", []):
            out.append((c["name"], running.get(e["name"]), c["sum"], bool(c.get("only_when_running"))))
    return out


# ------------------------------------------------------------------ install lists
def install_pairs(m, target):
    """-> sorted [(analysis file, destination file name)] for target 'pc' or 'image'."""
    if target not in TARGETS:
        raise ManifestError(f"unknown install target {target!r}")
    files = list(m["support_files"]) + (list(m["pc_only_files"]) if target == "pc" else [])
    for e in m["plugins"]:
        if target in e["deploy"]:
            files += e["files"]
    return sorted({(f, f) for f in files})


def extra_pairs(m, target):
    return sorted((x["src"], x.get("dst", x["src"].rsplit("/", 1)[-1])) for x in m["extra_files"] if target in x["targets"])


def install(m, target, dest, src=HERE, dry_run=False, out=sys.stdout):
    dest = dest.replace("\\", "/").rstrip("/")
    for f, d in install_pairs(m, target):
        line = f"analysis/{f}\t{dest}/{d}"
        if dry_run:
            out.write(line + "\n")
            continue
        os.makedirs(dest, exist_ok=True)
        shutil.copyfile(os.path.join(src, f), os.path.join(dest, d))
        out.write(line + "\n")


# ------------------------------------------------------------------ contracts
def contracts(m):
    """-> {interface name: contract dict} of the plugins that own one."""
    out = {}
    for e in m["plugins"]:
        c = e.get("contract")
        if c:
            if c["name"] in out:
                raise ManifestError(f"contract {c['name']!r} is declared twice")
            out[c["name"]] = dict(c, plugin=e["name"])
    return out


def contract_tables(m):
    """-> (SCHEMAS, SPECS, FIXTURES, LIVE) rows the manifest adds to check_contracts.py: interface -> schema file, interface -> spec file,
    fixture file -> interface, live file -> (interface, optional)."""
    schemas, specs, fixtures, live = {}, {}, {}, {}
    for name, c in contracts(m).items():
        schemas[name] = c["schema"]
        specs[name] = c["spec"]
        for fx in c["fixtures"]:
            fixtures[fx] = name
        for lv in c["live"]:
            live[lv["file"]] = (name, bool(lv["optional"]))
    return schemas, specs, fixtures, live


# ------------------------------------------------------------------ README block
def readme_block(m):
    rows = []

    def row(r):
        return f"| {r['label']} | {r['window']} | {r['text']} | {r['deps']} |"

    extra = {}
    for x in m.get("extra_rows", []):
        extra.setdefault(x["after"], []).append(x)
    for e in m["plugins"]:
        rows.append(row(e["readme"]))
        rows += [row(x) for x in extra.get(e["name"], [])]
    stems = "|".join(n for n in outputs_names(m))
    return (
        "\n".join(
            [README_BEGIN, "", "| plugin | window | what it produces | needs |", "|---|---|---|---|"]
            + rows
            + [
                "",
                f"Outputs under `--out` (default `<data-dir>/analysis`, `<data-dir>` = `$BMA_DATA_DIR`, default `./data`): `{stems}.jsonl` (plus `mixscore.jsonl` with `--mixscore`),",
                "",
                README_END,
            ]
        )
        + "\n"
    )


def readme_text(readme, m):
    """The README with its generated block refreshed (the block must exist between the markers)."""
    i, j = readme.find(README_BEGIN), readme.find(README_END)
    if i < 0 or j < i:
        raise ManifestError("README.md has no generated plugin-table block (markers missing)")
    return readme[:i] + readme_block(m).rstrip("\n") + readme[j + len(README_END) :]


def main(argv=None):
    import argparse

    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check")
    sub.add_parser("list")
    ip = sub.add_parser("install")
    ip.add_argument("--target", required=True, choices=TARGETS)
    ip.add_argument("--dest", required=True)
    ip.add_argument("--dry-run", action="store_true")
    rp = sub.add_parser("readme")
    rp.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    try:
        m = load()
        if a.cmd == "check":
            validate(m)
            print(f"manifest OK: {len(m['plugins'])} plugins")
        elif a.cmd == "list":
            print(" ".join(e["name"] for e in m["plugins"]))
        elif a.cmd == "install":
            install(m, a.target, a.dest, dry_run=a.dry_run)
        elif a.cmd == "readme":
            path = os.path.join(HERE, "README.md")
            with open(path, "r", encoding="utf-8", newline="") as f:
                cur = f.read()
            new = readme_text(cur, m)
            if a.write:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(new)
            else:
                sys.stdout.write(readme_block(m))
    except (ManifestError, OSError) as e:
        print(f"manifest.py: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
